"""Alert text from templates (T6a, LLM-0): {what, why, action} with text_src "template".

Every number comes from the incident's own metrics; every action comes from
docs/actions.yaml, which people write. Nothing here is generated by a model.
"""

import logging
from pathlib import Path
from typing import Any

import yaml

from vigil.backend.serialize import LEVEL_NAMES
from vigil.core.pipeline import Incident, IncidentMetric

log = logging.getLogger("vigil.narrate")

# label, lower-case name, unit, digits
METRIC = {
    "hr": ("Heart rate", "heart rate", "bpm", 0),
    "spo2": ("Blood oxygen", "blood oxygen", "%", 0),
    "rr": ("Respiration", "respiration", "br/min", 0),
    "skin_t": ("Skin temperature", "skin temperature", "°C", 1),
    "ppco2": ("Cabin CO₂", "cabin CO₂", "mmHg", 1),
    "press": ("Cabin pressure", "cabin pressure", "hPa", 0),
}
PATTERN_LABEL = {
    "hypoxia": "low blood oxygen",
    "tachycardia_rest": "fast heart rate at rest",
    "bradycardia": "slow heart rate",
    "fever_like": "rising skin temperature",
    "hypercapnia": "high cabin CO₂",
    "depressurization": "a cabin pressure drop",
    "sensor_artifact": "an unreliable sensor reading",
}
CTX_WORD = {"sleep": "asleep", "active": "exercising", "rest": "resting"}
DEFAULT_DIRECTION = {"spo2": "below", "ppco2": "above", "press": "below"}


def load_actions(path: str) -> dict[str, dict[str, list[str]]]:
    file = Path(path)
    if not file.is_file():
        log.warning("actions file %s not found: alerts carry no server text", path)
        return {}
    data = yaml.safe_load(file.read_text()) or {}
    return {
        pattern: {level: [str(s) for s in steps][:3] for level, steps in levels.items()}
        for pattern, levels in data.items()
    }


def _num(value: float, m: str) -> str:
    return f"{value:.{METRIC[m][3]}f}"


def _bound(value: float, m: str) -> str:
    """Range bounds keep one more decimal when rounding would move them (95.5 stays 95.5)."""
    digits = METRIC[m][3]
    extra = abs(value * 10**digits - round(value * 10**digits)) > 0.15
    return f"{value:.{digits + 1 if extra else digits}f}"


def _with_unit(value: float | None, m: str) -> str:
    if value is None:
        return "no reading"
    return f"{_num(value, m)} {METRIC[m][2]}"


def _minutes(n: int) -> str:
    n = max(1, n)
    if n == 1:
        return "1 minute"
    if n < 60:
        return f"{n} minutes"
    return f"{n // 60} h {n % 60:02d} m" if n % 60 else f"{n // 60} h"


def _direction(im: IncidentMetric) -> str:
    if im.z:
        return "below" if im.z < 0 else "above"
    if im.value is not None and im.usual:
        if im.value < im.usual[0]:
            return "below"
        if im.value > im.usual[1]:
            return "above"
    return DEFAULT_DIRECTION.get(im.m, "outside")


def _what(inc: Incident, im: IncidentMetric) -> str:
    label = METRIC[im.m][0]
    since = _minutes(im.since_min)
    if im.m == "ppco2":
        return f"{label} above the 3.0 mmHg limit for {since}"
    if im.m == "press":
        return f"{label} {'falling' if im.trend == 'falling' else 'low'} for {since}"
    ref = (
        "the safety limit"
        if inc.source == "hard" or not im.usual
        else "your usual range"
    )
    return f"{label} {_direction(im)} {ref} for {since}"


def _why(inc: Incident, im: IncidentMetric) -> str:
    parts = [f"{_with_unit(im.value, im.m)}"]
    if im.usual:
        parts[0] += f", usual {_bound(im.usual[0], im.m)}–{_bound(im.usual[1], im.m)}"
    parts[0] += "."
    others = []
    for other in list(inc.metrics.values())[1:]:
        if other.m not in METRIC:
            continue
        name = METRIC[other.m][1]
        if other.trend in ("rising", "falling"):
            others.append(f"{name} is {other.trend}")
        else:
            others.append(f"{name} is {_with_unit(other.value, other.m)}")
    if others:
        text = "; ".join(others)
        parts.append(text[0].upper() + text[1:] + ".")
    label = PATTERN_LABEL.get(inc.pattern or "")
    if label:
        ctx = inc.ctx.label if inc.ctx is not None else None
        vital = im.m in ("hr", "spo2", "rr", "skin_t")
        # "fast heart rate at rest" already says the context.
        said = inc.pattern == "tachycardia_rest"
        tail = (
            f" while {CTX_WORD[ctx]}" if ctx in CTX_WORD and vital and not said else ""
        )
        parts.append(f"This matches {label}{tail}.")
    return " ".join(parts)


def template_text(
    inc: Incident, actions: dict[str, dict[str, list[str]]]
) -> dict[str, Any] | None:
    """Text for a health or cabin incident, or None when there is nothing to say."""
    primary = inc.primary
    if not actions or inc.key != "incident" or primary not in METRIC:
        return None
    im = inc.metrics[primary]
    level = LEVEL_NAMES[max(inc.level, inc.peak_level)]
    by_level = actions.get(inc.pattern or "") or actions.get("default", {})
    steps = by_level.get(level) or actions.get("default", {}).get(level) or []
    return {"what": _what(inc, im), "why": _why(inc, im), "action": steps}
